import AppKit
import DroidsyncKit

final class SystemPasteboard: ClipboardPasteboard {
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        concealedType,
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard = NSPasteboard.general

    var changeCount: Int { pasteboard.changeCount }

    var holdsPrivateContent: Bool {
        guard let types = pasteboard.types else { return false }
        return !Self.privateTypes.isDisjoint(with: types)
    }

    func readText() -> String? {
        pasteboard.string(forType: .string)
    }

    func readImagePNG() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff) else { return nil }
        return Self.pngData(from: tiff)
    }

    /// Re-encodes any image format NSBitmapImageRep can decode (TIFF, JPEG, …) as PNG.
    static func pngData(from imageData: Data) -> Data? {
        NSBitmapImageRep(data: imageData)?.representation(using: .png, properties: [:])
    }

    func writeText(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    func writeImage(png: Data) {
        pasteboard.clearContents()
        pasteboard.setData(png, forType: .png)
    }
}
